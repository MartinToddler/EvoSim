/** Wall-clock, render and storage vocabulary that must never appear in a path. */
const HOST_FLAVOURED_TOKENS = [
  "PerSecond",
  "Ms",
  "Hz",
  "Fps",
  "Render",
  "Autosave",
  "Wall",
  "Frame",
];

function leafPaths(value: unknown, prefix = ""): string[] {
  if (Array.isArray(value)) {
    // An array of NUMBERS is one leaf — a per-biome table is a single decision.
    // An array of OBJECTS is descended into by index, because M17 made
    // `plants.resources` a five-element table of fourteen-field profiles, and
    // collapsing it to one leaf would hide seventy authoritative fields from
    // the tripwire that exists to notice exactly that.
    if (value.some((entry) => entry !== null && typeof entry === "object")) {
      return value.flatMap((entry, index) => leafPaths(entry, `${prefix}[${index}]`));
    }
    return [`${prefix}[]`];
  }
  if (value !== null && typeof value === "object") {
    return Object.keys(value).flatMap((key) =>
      leafPaths((value as Record<string, unknown>)[key], prefix ? `${prefix}.${key}` : key),
    );
  }
  return [prefix];
}

describe("hashed authoritative config surface", () => {
  it("matches the frozen inventory of hashed fields", () => {
    expect(leafPaths(DEFAULT_CONFIG).sort()).toEqual([...HASHED_CONFIG_LEAF_PATHS]);
  });

  it("contains no wall-clock, render or storage vocabulary", () => {
    const offenders = HASHED_CONFIG_LEAF_PATHS.filter((path) =>
      HOST_FLAVOURED_TOKENS.some((token) => path.includes(token)),
    );
    expect(offenders).toEqual([]);
  });
});
